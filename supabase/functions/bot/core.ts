// общий рубильник для владельцев
// deno-lint-ignore no-explicit-any
export async function ownerToggle(ctx: any, cmd: string, key: string, label: string, def: boolean) {
  if (!(await isOwner(ctx))) {
    await ctx.reply("Этой командой рулят только админы 🙅");
    return;
  }
  const arg = (ctx.match ?? "").trim().toLowerCase();
  if (arg !== "on" && arg !== "off") {
    const cur = await getFlag(key, def);
    await ctx.reply(`${label}: сейчас ${cur ? "✅ вкл" : "🚫 выкл"}.\nПереключить: /${cmd} on  или  /${cmd} off`);
    return;
  }
  const value = arg === "on";
  const { error } = await setFlag(key, value);
  if (error) {
    await ctx.reply("Ошибка 😬");
    return;
  }
  await ctx.reply(`${label}: ${value ? "✅ включено" : "🚫 выключено"}`);
}

// регистрация обработчиков — вызывается из index.ts строго по порядку: core → assistant → group
export function registerCore() {
  // --- запоминаем каждое сообщение, которое бот отправил (chat_id + message_id + текст),
  // чтобы по апдейту о реакции понять, что реакция именно на наше сообщение ---
  bot.api.config.use(async (prev, method, payload, signal) => {
    const res = await prev(method, payload, signal);
    // deno-lint-ignore no-explicit-any
    const m = res.ok ? (res.result as any) : null;
    // личку не журналим вообще (там пароли и личное)
    if (m && typeof m === "object" && "message_id" in m && m.chat?.id != null && m.chat?.type !== "private") {
      try {
        await supabase.from("bot_messages").upsert({
          chat_id: m.chat.id, message_id: m.message_id, text: trunc(m.text ?? m.caption ?? "", 300),
        });
      } catch (e) {
        console.error("bot_messages upsert failed", e);
      }
    }
    return res;
  });

  // --- антиспам-мьют: от замьюченного не доходит НИЧЕГО — текст, команды, стикеры, голосовые, медиа,
  // реакции, кнопки. Проверка первая, до всех обработчиков (и до Gemini). Главный админ под мьют не попадает.
  bot.use(async (ctx, next) => {
    const uid = ctx.from?.id;
    const chatId = ctx.chat?.id;
    if (uid != null && chatId != null && uname(ctx) !== SUPER_OWNER && (await isMuted(chatId, uid))) return;
    await next();
  });
}
