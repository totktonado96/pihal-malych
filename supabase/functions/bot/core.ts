// --- ИИ-режим: обращение к боту, команды словами, голосовые, прожарка, генератор ---
// антиспам: считаем дёргания бота человеком за окно; при переборе — "warn" (один раз послать) и мьют,
// пока мьют действует — "muted" (молчим). Возвращает "ok" | "warn" | "muted".
export async function spamCheck(chatId: number, userId: number): Promise<"ok" | "warn" | "muted"> {
  const now = Date.now();
  const { data: g } = await supabase.from("spam_guard").select("hits, window_start, muted_until")
    .eq("chat_id", chatId).eq("user_id", userId).maybeSingle();
  if (g?.muted_until && new Date(g.muted_until).getTime() > now) return "muted";
  const fresh = !g || now - new Date(g.window_start).getTime() > SPAM_WINDOW_SEC * 1000;
  const hits = fresh ? 1 : Number(g.hits ?? 0) + 1;
  const over = hits > SPAM_LIMIT;
  const { error } = await supabase.from("spam_guard").upsert({
    chat_id: chatId, user_id: userId,
    hits: over ? 0 : hits,
    window_start: fresh || over ? new Date(now).toISOString() : g.window_start,
    muted_until: over ? new Date(now + SPAM_MUTE_SEC * 1000).toISOString() : null,
  });
  if (error) console.error("spam_guard upsert failed", error);
  return over ? "warn" : "ok";
}

// человек сейчас в мьюте антиспама?
export async function isMuted(chatId: number, userId: number): Promise<boolean> {
  const { data: g } = await supabase.from("spam_guard").select("muted_until")
    .eq("chat_id", chatId).eq("user_id", userId).maybeSingle();
  return !!g?.muted_until && new Date(g.muted_until).getTime() > Date.now();
}

