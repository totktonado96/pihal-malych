// последние сообщения чата перед message_id (люди из chat_log + сам бот из bot_messages) — для контекста шутки
export async function recentMessages(chatId: number, beforeId: number, n = 50): Promise<string[]> {
  const { data: people } = await supabase.from("chat_log").select("message_id, user_name, text")
    .eq("chat_id", chatId).lt("message_id", beforeId).order("message_id", { ascending: false }).limit(n);
  const { data: mine } = await supabase.from("bot_messages").select("message_id, text")
    .eq("chat_id", chatId).lt("message_id", beforeId).order("message_id", { ascending: false }).limit(n);
  const rows = [
    // deno-lint-ignore no-explicit-any
    ...(people ?? []).map((m: any) => ({ id: Number(m.message_id), line: `${m.user_name}: ${m.text}` })),
    // deno-lint-ignore no-explicit-any
    ...(mine ?? []).filter((m: any) => m.text).map((m: any) => ({ id: Number(m.message_id), line: `Пихал Малыч (бот): ${m.text}` })),
  ].sort((a, b) => a.id - b.id);
  return rows.slice(-n).map((r) => trunc(r.line, 300));
}

// спросить Gemini, к чему шутка (по сообщениям до неё); null — контекста нет
export async function findContext(jokeText: string, before: string[]): Promise<string | null> {
  if (before.length < 3) return null; // не из чего
  const prompt = `Новая шутка: «${jokeText}»\n\nПоследние сообщения чата перед ней:\n${before.join("\n")}`;
  const found = await geminiText(CONTEXT_SYSTEM, [{ text: prompt }], { temperature: 0.4, maxTokens: 400, maxChars: 600 });
  if (!found || /^none\b/i.test(found) || found.length < 15) return null;
  return found;
}

// сохранить контекст к шутке и повесить кнопку на ответ «Записал»
export async function saveContext(jokeId: number, ctxText: string, chatId: number, sentMsgId: number) {
  const { error } = await supabase.from("jokes").update({ context: ctxText }).eq("id", jokeId);
  if (error) {
    console.error("context save failed", error);
    return;
  }
  try {
    await bot.api.editMessageText(chatId, sentMsgId, "Записал в копилку 📓\n📖 Контекст тоже запомнил", {
      reply_markup: new InlineKeyboard().text("📖 Контекст", `ctx:${jokeId}`),
    });
  } catch (_) { /* not modified */ }
}

// после /add (в фоне): по 40 сообщениям до шутки понять, к чему она; если контекст есть — сохранить и повесить кнопку
export async function attachContext(chatId: number, addMsgId: number, jokeId: number, jokeText: string, sentMsgId: number) {
  const before = await recentMessages(chatId, addMsgId, CTX_BEFORE);
  const found = await findContext(jokeText, before);
  if (found) await saveContext(jokeId, found, chatId, sentMsgId);
}

// сочинить шутку по просьбе и записать в копилку (автор — сам бот), контекст — из последних сообщений чата
// deno-lint-ignore no-explicit-any
export async function composeJoke(ctx: any, topic: string, requester: string) {
  const chatId = ctx.chat.id;
  const msgId = ctx.msg.message_id;
  const lines = await recentMessages(chatId, msgId, 50);
  const { data: top } = await supabase.from("jokes").select("text").order("likes", { ascending: false }).limit(8);
  const samples = (top ?? []).map((j) => `- ${trunc(j.text as string, 160)}`);
  const prompt = `Просьба от ${requester}${creatorNote(uname(ctx), topic)}: «${trunc(topic || "придумай шутку", 300)}»\n\n` +
    (lines.length ? `Последние сообщения чата:\n${lines.join("\n")}\n\n` : "") +
    (samples.length ? `Примеры шуток из копилки (стиль):\n${samples.join("\n")}` : "");
  const raw = await geminiText(COMPOSE_SYSTEM, [{ text: prompt }], { json: COMPOSE_SCHEMA, temperature: 1.1, maxTokens: 600 });
  let joke = "", context = "";
  try {
    const o = JSON.parse(raw ?? "");
    joke = String(o.joke ?? "").trim();
    context = String(o.context ?? "").trim();
  } catch {
    joke = (raw ?? "").trim();
  }
  if (!joke) {
    await bot.api.sendMessage(chatId, pick(AI_DOWN), { reply_parameters: { message_id: msgId } });
    return;
  }
  joke = trunc(joke, MAX_LEN);
  const { data: dup } = await supabase.from("jokes").select("id").ilike("text", joke).limit(1);
  if (dup && dup.length > 0) {
    await bot.api.sendMessage(chatId, `Такая уже есть в копилке: ${joke}`, { reply_parameters: { message_id: msgId } });
    return;
  }
  const ctxText = context.length >= 15 ? trunc(context, 600) : null;
  const { data: ins, error } = await supabase.from("jokes")
    .insert({ text: joke, added_by: "Пихал Малыч", context: ctxText }).select("id").single();
  if (error || !ins) {
    console.error("compose save failed", error);
    await bot.api.sendMessage(chatId, `Придумал, но сохранить не смог 😬\n\n${joke}`, { reply_parameters: { message_id: msgId } });
    return;
  }
  await bot.api.sendMessage(
    chatId,
    `😄 ${esc(joke)}\n\n<i>📓 записал в копилку · автор Пихал Малыч${ctxText ? " · 📖 контекст тоже" : ""}</i>`,
    { ...HTML, reply_parameters: { message_id: msgId }, reply_markup: jokeKeyboard(ins.id, 0, 0, !!ctxText) },
  );
  await supabase.rpc("bump_counter", { p_key: "composed", p_by: 1 });
}

// досье для прожарки: шутки человека из копилки + цифры
export async function buildDossier(name: string, username: string): Promise<string> {
  let { data: mine } = await supabase.from("jokes").select("text, likes, dislikes")
    .ilike("added_by", name).order("likes", { ascending: false }).limit(40);
  if (!mine || mine.length === 0) {
    ({ data: mine } = await supabase.from("jokes").select("text, likes, dislikes")
      .ilike("added_by", `%${name}%`).order("likes", { ascending: false }).limit(40));
  }
  const jokes = mine ?? [];
  // deno-lint-ignore no-explicit-any
  const likes = jokes.reduce((n: number, j: any) => n + (j.likes ?? 0), 0);
  // deno-lint-ignore no-explicit-any
  const dislikes = jokes.reduce((n: number, j: any) => n + (j.dislikes ?? 0), 0);
  const { count: total } = await supabase.from("jokes").select("*", { count: "exact", head: true });
  const { data: authors } = await supabase.rpc("author_stats");
  // deno-lint-ignore no-explicit-any
  const rank = (authors ?? []).findIndex((a: any) => String(a.author).toLowerCase() === name.toLowerCase());
  return [
    `Имя: ${name}${username ? ` (@${username})` : ""}`,
    username === LENYA ? `Это сам ${LN.nom} — герой всех шуток в копилке.` : "",
    `Всего шуток в копилке чата: ${total ?? 0}. Его шуток: ${jokes.length}` +
      (rank >= 0 ? ` (место ${rank + 1} среди авторов).` : jokes.length ? "." : " (ни одной)."),
    `Лайков на его шутках: ${likes}, дизлайков: ${dislikes}.`,
    jokes.length
      // deno-lint-ignore no-explicit-any
      ? "Его шутки (лучшие сверху):\n" + jokes.slice(0, 12).map((j: any) => `- ${trunc(j.text, 160)} (👍${j.likes} 👎${j.dislikes})`).join("\n")
      : "",
  ].filter(Boolean).join("\n");
}

export function jokeKeyboard(id: number, likes: number, dislikes: number, hasContext = false): InlineKeyboard {
  const kb = new InlineKeyboard()
    .text(`👍 ${likes}`, `like:${id}`)
    .text(`👎 ${dislikes}`, `dislike:${id}`);
  if (hasContext) kb.text("📖 Контекст", `ctx:${id}`);
  return kb;
}

// deno-lint-ignore no-explicit-any
export function inlineJokeText(j: any): string {
  return `<i>🤖 @${bot.botInfo.username} · №${j.pos} · 👍${j.likes} 👎${j.dislikes} · ${esc(j.jauthor)}</i>\n\n😄 ${esc(j.jtext)}`; // юзернейм берём живой — его можно менять в BotFather
}

