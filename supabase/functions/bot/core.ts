// это ответ на сообщение бота? (в форум-темах Telegram сам подставляет reply на корень темы — не считается)
// deno-lint-ignore no-explicit-any
export function isReplyToBot(ctx: any): boolean {
  const r = ctx.msg?.reply_to_message;
  if (!r?.from) return false;
  if (ctx.msg.is_topic_message && r.message_id === ctx.msg.message_thread_id) return false;
  return r.from.id === ctx.me?.id;
}

// запасной огрыз без нейросети — по контексту: что ответили и на что
export function pickSnap(botText: string, userText: string, name: string): string {
  const bt = botText.toLowerCase();
  const ut = userText.toLowerCase();
  const words = ut.split(/[^а-яёa-z0-9]+/i).filter(Boolean);
  let pool: string[];
  if (!ut.trim()) pool = SNAP_NOTEXT;
  else if (isFormal(userText)) pool = SNAP_POLITE;
  else if (/мам|мать|матер|бат[яь]|отец|отц|пап[ак]|бабк|бабушк/.test(ut)) pool = SNAP_MOM;
  else if (words.some((w) => /^(сам|сама|сами|само)$/.test(w))) pool = SNAP_SAM;
  else if (bt.includes("пиво")) pool = SNAP_PIVO;
  else if (/место|будку|сидеть|кыш|фу!/.test(bt)) pool = SNAP_PLACE;
  else pool = SNAP_GENERIC;
  return pick(pool).replace(/\{name\}/g, name);
}

// настройки запроса к Gemini
export type GeminiOpts = {
  timeoutMs?: number; // на одну попытку
  deadlineMs?: number; // на всё, с перебором моделей
  maxTokens?: number;
  maxChars?: number; // обрезка ответа
  temperature?: number;
  json?: unknown; // схема — тогда ответ строго JSON
  models?: string[]; // свой список моделей (личный ассистент)
  thinking?: string; // уровень размышлений: minimal | low | medium | high
  accept?: (out: string) => boolean; // проверка ответа; не прошёл — пробуем следующую модель
};

// один запрос к Gemini. parts — текст и/или аудио. Возвращает: строку — ответ; "blocked" — Google отклонил
// сам запрос по содержанию (PROHIBITED_CONTENT/SAFETY — другие модели откажут так же);
// null — сеть/лимит/503, стоит попробовать другую модель
export async function geminiCall(model: string, system: string, parts: unknown[], o: GeminiOpts): Promise<string | null> {
  const safetySettings = [
    "HARM_CATEGORY_HARASSMENT", "HARM_CATEGORY_HATE_SPEECH",
    "HARM_CATEGORY_SEXUALLY_EXPLICIT", "HARM_CATEGORY_DANGEROUS_CONTENT",
  ].map((category) => ({ category, threshold: "BLOCK_NONE" }));
  try {
    const res = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`, {
      method: "POST",
      headers: { "content-type": "application/json", "x-goog-api-key": GEMINI_KEY },
      body: JSON.stringify({
        system_instruction: { parts: [{ text: system }] },
        contents: [{ role: "user", parts }],
        generationConfig: {
          temperature: o.temperature ?? 1.1,
          maxOutputTokens: o.maxTokens ?? 400,
          thinkingConfig: { thinkingLevel: o.thinking ?? "low" },
          ...(o.json ? { responseMimeType: "application/json", responseSchema: o.json } : {}),
        },
        safetySettings,
      }),
      signal: AbortSignal.timeout(o.timeoutMs ?? 15_000),
    });
    if (!res.ok) {
      console.error("gemini", model, res.status, (await res.text()).slice(0, 200));
      return null; // 404 — модели нет, 429 — лимит, 503 — перегружена
    }
    const data = await res.json();
    const cand = data.candidates?.[0];
    // deno-lint-ignore no-explicit-any
    const parts2: any[] = cand?.content?.parts ?? [];
    const out = parts2.filter((p) => !p.thought).map((p) => p.text ?? "").join("")
      .trim().replace(/^["«»“”'\s]+|["«»“”'\s]+$/g, "").trim();
    if (out) return trunc(out, o.json ? 4000 : (o.maxChars ?? 300));
    const why = data.promptFeedback?.blockReason ?? cand?.finishReason ?? "?";
    console.error("gemini empty", model, why);
    const blocked = !!data.promptFeedback?.blockReason ||
      ["SAFETY", "PROHIBITED_CONTENT", "BLOCKLIST", "SPII"].includes(cand?.finishReason);
    return blocked ? "blocked" : null;
  } catch (e) {
    console.error("gemini failed", model, String(e).slice(0, 200));
    return null;
  }
}

// запрос с перебором моделей: два круга по списку (503 «high demand» на бесплатном тарифе — обычное дело),
// общий дедлайн. "blocked" — отказ по содержанию, дальше не перебираем. null — никто не ответил.
export async function geminiAsk(system: string, parts: unknown[], o: GeminiOpts = {}): Promise<string | null> {
  if (!GEMINI_KEY) return null;
  const deadline = Date.now() + (o.deadlineMs ?? 30_000);
  for (let round = 0; round < 2; round++) {
    for (const model of o.models ?? GEMINI_MODELS) {
      const left = deadline - Date.now();
      if (left < 3000) return null;
      const r = await geminiCall(model, system, parts, { ...o, timeoutMs: Math.min(o.timeoutMs ?? 15_000, left) });
      if (r && r !== "blocked" && o.accept && !o.accept(r)) {
        console.error("gemini rejected output", model, r.slice(0, 200));
        continue; // зациклилась или битый JSON — следующая модель
      }
      if (r) return r; // текст или "blocked"
    }
  }
  return null;
}

// то же, но отказ по содержанию = null (для задач, где мягкой версии нет)
export async function geminiText(system: string, parts: unknown[], o: GeminiOpts = {}): Promise<string | null> {
  const r = await geminiAsk(system, parts, o);
  return r && r !== "blocked" ? r : null;
}

// огрыз через Gemini (event — что случилось: «X ответил: …» / «X поставил реакцию …»);
// null — если ключа нет, все модели легли/лимит, или Google отклонил запрос даже в мягком варианте
export async function geminiSnap(botText: string, event: string, formal = false): Promise<string | null> {
  const prompt = `Моё сообщение в чате: «${trunc(botText, 300) || "(без текста)"}»\n${event}\nОгрызнись.`;
  const r = await geminiAsk((formal ? SNAP_SYSTEM_POLITE : SNAP_SYSTEM) + (isNight() ? NIGHT_ADDENDUM : ""), [{ text: prompt }]);
  if (r !== "blocked") return r;
  // отказ по содержанию — один раз пробуем мягкую инструкцию без мата
  const soft = await geminiAsk(SNAP_SYSTEM_SOFT, [{ text: prompt }]);
  return soft && soft !== "blocked" ? soft : null;
}

// итоговый огрыз на ответ: нейросеть, а если не смогла — фраза из списка
export async function makeSnap(botText: string, userText: string, name: string, note = ""): Promise<{ text: string; ai: boolean }> {
  const formal = isFormal(userText); // на «вы» — отвечаем как интеллигент в пенсне
  const ai = await geminiSnap(botText, `${name}${note} ответил на него: «${trunc(userText, 400) || "(без текста — стикер, картинка или голосовое)"}»`, formal);
  return ai ? { text: ai, ai: true } : { text: pickSnap(botText, userText, name), ai: false };
}

