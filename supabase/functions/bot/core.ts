// --- утилиты ---
export function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function trunc(s: string, n = 150): string {
  return s.length > n ? s.slice(0, n - 1) + "…" : s;
}

export function fmtDate(iso: string): string {
  const d = new Date(iso);
  const p = (n: number) => String(n).padStart(2, "0");
  return `${p(d.getUTCDate())}.${p(d.getUTCMonth() + 1)}.${d.getUTCFullYear()}`;
}

// deno-lint-ignore no-explicit-any
export function uname(ctx: any): string {
  return (ctx.from?.username ?? "").toLowerCase();
}

// есть ли в сообщении ссылка: сначала по entity'ам от Telegram (url / скрытая ссылка
// в тексте), плюс запасной разбор текста — на случай, когда entity'ев нет
// deno-lint-ignore no-explicit-any
export function hasLink(ctx: any): boolean {
  // deno-lint-ignore no-explicit-any
  const ents: any[] = [...(ctx.msg?.entities ?? []), ...(ctx.msg?.caption_entities ?? [])];
  if (ents.some((e) => e.type === "url" || e.type === "text_link")) return true;
  const text = ctx.msg?.text ?? ctx.msg?.caption ?? "";
  return /(https?:\/\/|www\.|\bt\.me\/|[a-zа-я0-9-]+\.(ru|com|net|org|io|me|tv|ua|kz|by|us|uk|de|info|online|site|app|dev|xyz|link|ly|cc|to|gg|ai|club|shop|store|pro|biz)(\/|\?|$|\s))/i
    .test(text);
}

// deno-lint-ignore no-explicit-any
export async function isOwner(ctx: any): Promise<boolean> {
  const u = uname(ctx);
  if (u === SUPER_OWNER) return true;
  if (!u) return false;
  const { data } = await supabase.from("owners").select("username").eq("username", u).maybeSingle();
  return !!data;
}

